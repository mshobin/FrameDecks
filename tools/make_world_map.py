STEP = 2.5                 # degrees between dots
TOP, BOTTOM = 80, -56      # latitudes shown
W, H = 360, TOP - BOTTOM   # viewBox: 1 unit per degree


def inside(x, y, poly):
    hit = False
    for i in range(len(poly)):
        (x1, y1), (x2, y2) = poly[i], poly[i - 1]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            hit = not hit
    return hit


def main():
    dots = []
    lat = TOP - STEP / 2
    while lat > BOTTOM:
        lon = -180 + STEP / 2
        while lon < 180:
            if any(inside(lon, lat, p) for p in LAND.values()):
                dots.append(f"M{lon + 180:g} {TOP - lat:g}h0")
            lon += STEP
        lat -= STEP
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" preserveAspectRatio="xMidYMid slice">'
           f'<path d="{"".join(dots)}" stroke="#d9b45a" stroke-width="1.05" stroke-linecap="round" fill="none"/></svg>')
    out = Path(__file__).resolve().parent.parent / "app" / "img" / "kc-world.svg"
    out.write_text(svg, encoding="utf-8")
    print(f"{len(dots)} dots, {len(svg) // 1024} KB -> {out}")


if __name__ == "__main__":
    main()
