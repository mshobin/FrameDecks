"""FrameDecks 9.6 - one set of design tokens for the desktop app and the website.

The desktop app's CSS is the source (app/css/dashboard.css, console.css, theme.css: the Gold & Navy look, dark and
light, the level colours, radii, spacing and type sizes). This writes them to hosted/src/app/tokens.css as --fd-*
custom properties (dark on :root, light on html.fd-light), and the website's own variables point at them
(globals.css, light.css), so the website shows the app's palette and changes with it.

    python tools/design_tokens.py           # write hosted/src/app/tokens.css
    python tools/design_tokens.py --check   # fail when tokens.css is not what the app's CSS says (CI, tests)

Standard library only.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
APP = ROOT / "app" / "css"
OUT = ROOT / "hosted" / "src" / "app" / "tokens.css"
SOURCES = ("palette.css", "dashboard.css", "console.css", "theme.css")      # the app's load order
DARK = {":root", ':root,html[data-theme="dark"]', 'html[data-theme="dark"]'}
LIGHT = {'html[data-theme="light"]'}
# the app's name -> the token's name (and what it is for)
NAMES = [
    ("app-bg", "page"), ("surface", "cards and panels"), ("raised", "raised controls"), ("panel-2", "quiet panels"),
    ("field", "text fields"), ("line", "lines"), ("line-soft", "quiet lines"), ("ink", "text"), ("muted", "secondary text"),
    ("faint", "tertiary text"), ("gold", "the main action"), ("gold-strong", "gold text"), ("gold-soft", "gold tint"),
    ("gold-ink", "text on gold"), ("live", "on screen now"), ("live-soft", "on screen tint"), ("red", "stop, hide"),
    ("red-soft", "red tint"), ("accent", "selection"), ("accent-soft", "selection tint"),
    ("lv-frame", "Frames"), ("lv-frame-soft", "Frames, tint"), ("lv-deck", "Decks"), ("lv-deck-soft", "Decks, tint"),
    ("lv-content", "Content"), ("lv-content-soft", "Content, tint"),
]
SHARED = ["r-1", "r-2", "r-3", "r-4", "fs-headline", "fs-title", "fs-section", "fs-body", "fs-caption", "ease"]
BLOCK = re.compile(r"(?m)^([^{}@/\n][^{}\n]*?)\{([^{}]*)\}")
DECL = re.compile(r"--([\w-]+)\s*:\s*([^;}]+)")


def collect():
    """{'dark': {name: value}, 'light': {...}} from the app's top-level token blocks, later ones winning."""
    out = {"dark": {}, "light": {}}
    for f in SOURCES:
        text = re.sub(r"/\*.*?\*/", "", (APP / f).read_text(encoding="utf-8"), flags=re.S)
        for sel, body in BLOCK.findall(text):
            sel = re.sub(r"\s+", "", sel)
            which = "dark" if sel in {re.sub(r"\s+", "", s) for s in DARK} else "light" if sel in {re.sub(r"\s+", "", s) for s in LIGHT} else None
            if not which:
                continue
            for k, v in DECL.findall(body):
                out[which][k] = v.strip()
    for k, v in out["dark"].items():                   # the light theme inherits what it does not set
        out["light"].setdefault(k, v)
    return out


def resolve(value, table, depth=0):
    """var(--x) and var(--x,fallback) replaced by their values from the same theme."""
    def one(m):
        name, fb = m.group(1), m.group(2)
        if name in table and depth < 8:
            return resolve(table[name], table, depth + 1)
        return fb.strip() if fb else m.group(0)
    return re.sub(r"var\(--([\w-]+)\s*(?:,\s*([^()]*(?:\([^()]*\))?[^()]*))?\)", one, value)


def render():
    t = collect()
    lines = ["/* GENERATED by tools/design_tokens.py from the FrameDecks desktop app's CSS (app/css). Do not edit:",
             " * change the app's tokens and run the tool. The website's variables (globals.css, light.css) point here. */",
             ":root {"]
    for name, what in NAMES:
        lines.append("  --fd-%s: %s; /* %s */" % (name, resolve(t["dark"][name], t["dark"]), what))
    for name in SHARED:
        lines.append("  --fd-%s: %s;" % (name, resolve(t["dark"][name], t["dark"])))
    lines += ["}", "", "html.fd-light {"]
    for name, _what in NAMES:
        lines.append("  --fd-%s: %s;" % (name, resolve(t["light"][name], t["light"])))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv):
    text = render()
    if "--check" in argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            print("hosted/src/app/tokens.css is not the app's tokens: run python tools/design_tokens.py")
            return 1
        print("design tokens: the website has the app's %d tokens" % (len(NAMES) + len(SHARED)))
        return 0
    OUT.write_text(text, encoding="utf-8")
    print("wrote", OUT.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
